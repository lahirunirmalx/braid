"""Generate the Braid logo SVGs: three phase-shifted strands with true
over/under crossings (the descending strand passes over), node dots at the
strand ends, and a wordmark. Writes light and dark variants."""
import math
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else "."

STRANDS = ["#0EA5A4", "#F59E0B", "#6366F1"]   # teal, amber, indigo
THEMES = {
    "light": {"bg": "#FFFFFF", "text": "#111827", "sub": "#4B5563"},
    "dark":  {"bg": "#0D1117", "text": "#F3F4F6", "sub": "#9CA3AF"},
}

X0, X1 = 30.0, 170.0     # strand span inside the mark
CY, AMP = 80.0, 40.0     # centre line and amplitude
PERIOD = (X1 - X0)       # one full period across the mark
W_STROKE, W_HALO = 12.0, 22.0
WIN = 11.0               # half-width of the redrawn "over" segment


def y_at(i, x):
    phase = 2.0 * math.pi * i / 3.0
    return CY + AMP * math.sin(2.0 * math.pi * (x - X0) / PERIOD + phase)


def dy_at(i, x):
    phase = 2.0 * math.pi * i / 3.0
    k = 2.0 * math.pi / PERIOD
    return AMP * k * math.cos(k * (x - X0) + phase)


def path(i, xa, xb, step=1.0):
    pts = []
    x = xa
    while x < xb:
        pts.append((x, y_at(i, x)))
        x += step
    pts.append((xb, y_at(i, xb)))
    d = "M%.2f %.2f" % pts[0] + "".join(" L%.2f %.2f" % p for p in pts[1:])
    return d


def crossings():
    found = []
    for a in range(3):
        for b in range(a + 1, 3):
            x = X0
            prev = y_at(a, x) - y_at(b, x)
            while x < X1:
                nx = x + 0.05
                cur = y_at(a, nx) - y_at(b, nx)
                if prev == 0 or (prev < 0) != (cur < 0):
                    xc = (x + nx) / 2.0
                    if X0 + 4 < xc < X1 - 4:
                        # SVG y grows downward: the strand with larger dy/dx
                        # is descending on screen; it goes over.
                        over = a if dy_at(a, xc) > dy_at(b, xc) else b
                        found.append((xc, over))
                prev = cur
                x = nx
    return sorted(found)


def mark(theme, ox=0.0, oy=0.0):
    t = THEMES[theme]
    parts = ['<g transform="translate(%.1f %.1f)" fill="none" '
             'stroke-linecap="round" stroke-linejoin="round">' % (ox, oy)]
    for i, c in enumerate(STRANDS):
        parts.append('<path d="%s" stroke="%s" stroke-width="%.1f"/>'
                     % (path(i, X0, X1), c, W_STROKE))
    for xc, over in crossings():
        halo = path(over, xc - WIN * 0.7, xc + WIN * 0.7, 0.5)
        seg = path(over, xc - WIN, xc + WIN, 0.5)
        parts.append('<path d="%s" stroke="%s" stroke-width="%.1f" stroke-linecap="butt"/>'
                     % (halo, t["bg"], W_HALO))
        parts.append('<path d="%s" stroke="%s" stroke-width="%.1f" stroke-linecap="round"/>'
                     % (seg, STRANDS[over], W_STROKE))
    parts.append('</g><g transform="translate(%.1f %.1f)">' % (ox, oy))
    for i, c in enumerate(STRANDS):
        for x in (X0, X1):
            parts.append('<circle cx="%.2f" cy="%.2f" r="10" fill="%s" stroke="%s" stroke-width="4.5"/>'
                         % (x, y_at(i, x), t["bg"], c))
    parts.append('</g>')
    return "".join(parts)


FONT = ("font-family=\"'Inter','Segoe UI','Helvetica Neue',Helvetica,Arial,"
        "sans-serif\"")


def write(name, body, w, h, theme):
    t = THEMES[theme]
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" '
           'viewBox="0 0 %d %d" role="img" aria-label="Braid">'
           '<!-- SPDX-License-Identifier: CC-BY-SA-4.0 | SPDX-FileCopyrightText: 2026 lahiru | generated by tools/gen_logo.py -->'
           '<title>Braid</title><rect width="100%%" height="100%%" fill="%s"/>%s</svg>\n'
           % (w, h, w, h, t["bg"], body))
    with open(os.path.join(OUT, name), "w", encoding="ascii") as f:
        f.write(svg)


for theme in THEMES:
    t = THEMES[theme]
    # icon: square mark
    write("braid-mark-%s.svg" % theme, mark(theme, 0.0, 20.0), 200, 200, theme)
    # banner: mark + wordmark + tagline
    words = ('<text x="222" y="98" %s font-size="78" font-weight="700" '
             'letter-spacing="-1" fill="%s">braid</text>'
             '<text x="226" y="128" %s font-size="17" fill="%s">'
             'one mesh, many carriers</text>' % (FONT, t["text"], FONT, t["sub"]))
    write("braid-logo-%s.svg" % theme, mark(theme, 4.0, 0.0) + words, 560, 160, theme)
print("crossings:", ["%.1f/%d" % c for c in crossings()])
