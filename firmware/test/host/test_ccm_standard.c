#define NVECS (sizeof vecs / sizeof vecs[0])

static void run_vec(br_crypto_t *c, const ccm_vec_t *v)
{
    char ctx[32];
    uint8_t ct[40], tag[8], pt[40], aad[16], ctb[40], tgb[8], key[16], nonce[13];
    snprintf(ctx, sizeof ctx, "RFC3610 #%d", v->pkt);
    tu_ctx(ctx);

    /* encrypt: ciphertext and tag byte-exact */
    memset(ct, 0xAA, sizeof ct);
    memset(tag, 0xAA, sizeof tag);
    CHECK_ERR(br_ccm_encrypt(c, v->key, v->nonce, v->hdr, v->hdr_len, v->pt, v->pt_len, ct, tag), BR_OK);
    CHECK_MEM(v->ct, ct, v->pt_len);
    CHECK_MEM(v->tag, tag, 8);

    /* decrypt the published ciphertext + tag */
    memset(pt, 0xAA, sizeof pt);
    CHECK_ERR(br_ccm_decrypt(c, v->key, v->nonce, v->hdr, v->hdr_len, v->ct, v->pt_len, v->tag, pt), BR_OK);
    CHECK_MEM(v->pt, pt, v->pt_len);

    /* in-place decrypt */
    memcpy(ctb, v->ct, v->pt_len);
    CHECK_ERR(br_ccm_decrypt(c, v->key, v->nonce, v->hdr, v->hdr_len, ctb, v->pt_len, v->tag, ctb), BR_OK);
    CHECK_MEM(v->pt, ctb, v->pt_len);

    /* single-bit flips must fail authentication and release no plaintext */
    for (int what = 0; what < 4; what++) {
        size_t n = (what == 0) ? v->pt_len : (what == 1) ? 8u : (what == 2) ? v->hdr_len : 13u;
        for (size_t byte = 0; byte < n; byte++) {
            for (unsigned bit = 0; bit < 8; bit += (what == 3 || what == 1) ? 1u : 7u) {
                memcpy(ctb, v->ct, v->pt_len);
                memcpy(tgb, v->tag, 8);
                memcpy(aad, v->hdr, v->hdr_len);
                memcpy(nonce, v->nonce, 13);
                memcpy(key, v->key, 16);
                if (what == 0) {
                    ctb[byte] ^= (uint8_t)(1u << bit);
                } else if (what == 1) {
                    tgb[byte] ^= (uint8_t)(1u << bit);
                } else if (what == 2) {
                    aad[byte] ^= (uint8_t)(1u << bit);
                } else {
                    nonce[byte] ^= (uint8_t)(1u << bit);
                }
                memset(pt, 0xAA, sizeof pt);
                br_err_t e = br_ccm_decrypt(c, key, nonce, aad, v->hdr_len, ctb, v->pt_len, tgb, pt);
                CHECK_ERR(e, BR_ERR_AUTH);
                /* header: pt_out is zeroed on BR_ERR_AUTH */
                bool zero = true;
                for (size_t i = 0; i < v->pt_len; i++) {
                    if (pt[i] != 0) {
                        zero = false;
                    }
                }
                CHECK_MSG(zero, "plaintext released or not wiped after BR_ERR_AUTH");
                CHECK_MSG(v->pt_len == 0 || memcmp(pt, v->pt, v->pt_len) != 0, "authentic plaintext leaked");
            }
        }
    }
}

int main(void)
{
    br_crypto_t c;
    memset(&c, 0, sizeof c);
    CHECK_ERR(br_crypto_init(&c), BR_OK);

    for (size_t i = 0; i < NVECS; i++) {
        run_vec(&c, &vecs[i]);
    }

    TU_SKIP("RFC 3610 packet vectors #7-#12, #19-#24 (M = 10)",
            "br_ccm_encrypt/decrypt fix the tag at 8 bytes (BR_CCM_TAG_LEN); no 10-byte tag API");
    TU_SKIP("NIST SP 800-38C Appendix C example C.1 (Klen 128, Tlen 32)",
            "4-byte tag unsupported: br_ccm_* fix the tag at 8 bytes (also C.1 uses a 7-byte nonce, API takes only 13)");

    br_crypto_free(&c);
    printf("test_ccm_standard: %zu RFC 3610 vectors (M=8, L=2) exercised\n", (size_t)NVECS);
    return tu_summary("test_ccm_standard");
}
