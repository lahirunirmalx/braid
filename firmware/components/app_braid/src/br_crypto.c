br_err_t br_key_check_field(const uint8_t *key, size_t key_len)
{
    if (key == NULL || key_len == 0u) {
        return BR_ERR_ARG;
    }
    /* All-equal (all-zero included): accumulate without early exit. */
    uint8_t spread = 0u;
    for (size_t i = 1u; i < key_len; i++) {
        spread = (uint8_t)(spread | (uint8_t)(key[i] ^ key[0]));
    }
    uint32_t hit = (uint32_t)(((uint32_t)spread - 1u) >> 8) & 1u; /* 1 iff spread == 0 */

    if (key_len == BR_SHA256_LEN) {
        uint8_t h[BR_SHA256_LEN];
        if (mbedtls_sha256(key, key_len, h, 0) != 0) {
            mbedtls_platform_zeroize(h, sizeof h);
            return BR_ERR_CRYPTO;
        }
        for (size_t e = 0u; e < 256u; e++) {
            uint32_t d = 0u;
            for (size_t j = 0u; j < 8u; j++) {
                d |= (uint32_t)(h[j] ^ s_test_kmesh_hash8[e][j]);
            }
            hit |= ((d - 1u) >> 8) & 1u; /* d in 0..255: 1 iff d == 0 */
        }
        mbedtls_platform_zeroize(h, sizeof h);
    }
    return (hit != 0u) ? BR_ERR_AUTH : BR_OK;
}
