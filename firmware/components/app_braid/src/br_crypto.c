/* Utilities                                                                  */
/* ------------------------------------------------------------------------- */

br_err_t br_ct_equal(const uint8_t *a, const uint8_t *b, size_t len)
{
    if (len > 0u && (a == NULL || b == NULL)) {
        return BR_ERR_ARG;
    }
    const volatile uint8_t *va = a;
    const volatile uint8_t *vb = b;
    volatile uint8_t diff = 0u;
    for (size_t i = 0u; i < len; i++) {
        diff = (uint8_t)(diff | (uint8_t)(va[i] ^ vb[i]));
    }
    return (diff == 0u) ? BR_OK : BR_ERR_AUTH;
}

void br_secure_zero(void *p, size_t len)
{
    if (p == NULL || len == 0u) {
        return;
    }
    mbedtls_platform_zeroize(p, len);
}

