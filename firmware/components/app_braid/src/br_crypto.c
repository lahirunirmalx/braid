/* Nonce and AAD (8.3)                                                        */
/* ------------------------------------------------------------------------- */

br_err_t br_ccm_nonce(uint8_t dir, uint16_t src_id, uint16_t dst_id, uint8_t session_id,
                      uint32_t ctr_hi, uint16_t seq, uint8_t nonce_out[BR_CCM_NONCE_LEN])
{
    if (nonce_out == NULL || dir > BR_DIR_BUNDLE) {
        return BR_ERR_ARG;
    }
    if (dir == BR_DIR_BUNDLE) {
        /* 8.6: 0x02 || N u16 || bundle_no u32 || 0x00 x 6 */
        if (dst_id != 0u || session_id != 0u || seq != 0u) {
            return BR_ERR_ARG;
        }
        memset(nonce_out, 0, BR_CCM_NONCE_LEN);
        nonce_out[0] = dir;
        br_wr_le16(&nonce_out[1], src_id);
        br_wr_le32(&nonce_out[3], ctr_hi);
        return BR_OK;
    }
    nonce_out[0] = dir;
    br_wr_le16(&nonce_out[1], src_id);
    br_wr_le16(&nonce_out[3], dst_id);
    nonce_out[5] = session_id;
    br_wr_le32(&nonce_out[6], ctr_hi);
    br_wr_le16(&nonce_out[10], seq);
    nonce_out[12] = 0u;
    return BR_OK;
}

br_err_t br_ccm_aad(const uint8_t *frame, size_t frame_len, uint32_t ctr_hi, size_t clear_len,
                    uint8_t *aad_out, size_t cap, size_t *aad_len)
{
    if (frame == NULL || aad_out == NULL || aad_len == NULL) {
        return BR_ERR_ARG;
    }
    if (frame_len < 2u) {
        return BR_ERR_DECODE;
    }
    const size_t hl = br_hdr_len_for_type(frame[BR_OFF_TYPE]);
    if (frame_len < hl) {
        return BR_ERR_DECODE;
    }
    const bool seek = (hl == BR_HDR_LEN_SEEK);
    const size_t off_sid = seek ? BR_OFF_SESSION_ID_SEEK : BR_OFF_SESSION_ID;
    const size_t off_seq = seek ? BR_OFF_SEQ_SEEK : BR_OFF_SEQ;
    const size_t off_len = seek ? BR_OFF_LEN_SEEK : BR_OFF_LEN;
    if (clear_len > frame[off_len]) {
        return BR_ERR_ARG;
    }
    if (frame_len - hl < clear_len) {
        return BR_ERR_DECODE;
    }
    const size_t total = BR_E2E_HDR_LEN + 4u + clear_len;
    if (cap < total) {
        return BR_ERR_TOO_BIG;
    }
    memcpy(&aad_out[0], &frame[0], 6u);
    aad_out[6] = frame[off_sid];
    memcpy(&aad_out[7], &frame[off_seq], 2u);
    aad_out[9] = frame[off_len];
    br_wr_le32(&aad_out[10], ctr_hi);
    if (clear_len > 0u) {
        memcpy(&aad_out[14], &frame[hl], clear_len);
    }
    *aad_len = total;
    return BR_OK;
}

/* ------------------------------------------------------------------------- */
/* AES-128-CCM, M = 8, L = 2 (RFC 3610)                                       */
/* ------------------------------------------------------------------------- */

typedef struct {
    mbedtls_aes_context aes;
    uint8_t x[CCM_BLOCK];    /* CBC-MAC state */
    uint8_t ctr[CCM_BLOCK];  /* counter block A_i */
    uint8_t s[CCM_BLOCK];    /* key stream block S_i */
    uint8_t tmp[CCM_BLOCK];
    size_t  pos;             /* bytes absorbed into the current MAC block */
} ccm_state_t;

static int ccm_enc_block(ccm_state_t *st, const uint8_t in[CCM_BLOCK], uint8_t out[CCM_BLOCK])
{
    int ret = mbedtls_aes_crypt_ecb(&st->aes, MBEDTLS_AES_ENCRYPT, in, st->tmp);
    memcpy(out, st->tmp, CCM_BLOCK);
    return ret;
}

static int ccm_mac_bytes(ccm_state_t *st, const uint8_t *p, size_t n)
{
    for (size_t i = 0u; i < n; i++) {
        st->x[st->pos] = (uint8_t)(st->x[st->pos] ^ p[i]);
        st->pos++;
        if (st->pos == CCM_BLOCK) {
            int ret = ccm_enc_block(st, st->x, st->x);
            if (ret != 0) {
                return ret;
            }
            st->pos = 0u;
        }
    }
    return 0;
}

static int ccm_mac_pad(ccm_state_t *st)
{
    if (st->pos == 0u) {
        return 0;
    }
    st->pos = 0u;
    return ccm_enc_block(st, st->x, st->x);
}

/* Set the key and absorb B0 and the AAD; leaves the counter at A_0. */
static int ccm_start(ccm_state_t *st, const uint8_t key[BR_AES_KEY_LEN],
                     const uint8_t nonce[BR_CCM_NONCE_LEN],
                     const uint8_t *aad, size_t aad_len, size_t msg_len)
{
    memset(st, 0, sizeof *st);
    mbedtls_aes_init(&st->aes);
    int ret = mbedtls_aes_setkey_enc(&st->aes, key, 128u);
    if (ret != 0) {
        return ret;
    }
    /* B0: flags = Adata << 6 | ((M - 2) / 2) << 3 | (L - 1); nonce; l(m) BE16. */
    uint8_t b0[CCM_BLOCK];
    b0[0] = (uint8_t)(((aad_len > 0u) ? 0x40u : 0u) |
                      (((BR_CCM_TAG_LEN - 2u) / 2u) << 3) | (CCM_L - 1u));
    memcpy(&b0[1], nonce, BR_CCM_NONCE_LEN);
    b0[14] = (uint8_t)(msg_len >> 8);
    b0[15] = (uint8_t)(msg_len & 0xFFu);
    ret = ccm_enc_block(st, b0, st->x);
    mbedtls_platform_zeroize(b0, sizeof b0);
    if (ret != 0) {
        return ret;
    }
    if (aad_len > 0u) {
        /* 0 < l(a) < 2^16 - 2^8: two-byte big-endian length prefix. */
        const uint8_t alen[2] = { (uint8_t)(aad_len >> 8), (uint8_t)(aad_len & 0xFFu) };
        ret = ccm_mac_bytes(st, alen, sizeof alen);
        if (ret == 0) {
            ret = ccm_mac_bytes(st, aad, aad_len);
        }
        if (ret == 0) {
            ret = ccm_mac_pad(st);
        }
        if (ret != 0) {
            return ret;
        }
    }
    /* A_i = (L - 1) || nonce || i BE16 */
    st->ctr[0] = (uint8_t)(CCM_L - 1u);
    memcpy(&st->ctr[1], nonce, BR_CCM_NONCE_LEN);
    return 0;
}

static int ccm_keystream(ccm_state_t *st, uint16_t i)
{
    st->ctr[14] = (uint8_t)(i >> 8);
    st->ctr[15] = (uint8_t)(i & 0xFFu);
    return ccm_enc_block(st, st->ctr, st->s);
}

/* tag = first 8 bytes of (CBC-MAC XOR S_0). */
static int ccm_finish_tag(ccm_state_t *st, uint8_t tag[BR_CCM_TAG_LEN])
{
    int ret = ccm_mac_pad(st);
    if (ret == 0) {
        ret = ccm_keystream(st, 0u);
    }
    if (ret == 0) {
        for (size_t i = 0u; i < BR_CCM_TAG_LEN; i++) {
            tag[i] = (uint8_t)(st->x[i] ^ st->s[i]);
        }
    }
    return ret;
}

static void ccm_wipe(ccm_state_t *st)
{
    mbedtls_aes_free(&st->aes);
    mbedtls_platform_zeroize(st, sizeof *st);
}

/* NULL-pointer rules (checked before the context state). */
static bool ccm_ptrs_ok(const uint8_t *key, const uint8_t *nonce, const uint8_t *aad,
                        size_t aad_len, const uint8_t *in, size_t len, const uint8_t *out,
                        const uint8_t *tag)
{
    return key != NULL && nonce != NULL && tag != NULL &&
           !(aad == NULL && aad_len > 0u) && !(len > 0u && (in == NULL || out == NULL));
}

/* Range rules (checked after the context state). */
static bool ccm_lens_ok(size_t aad_len, size_t len)
{
    return aad_len <= BR_AAD_MAX_LEN && len <= 255u;
}

br_err_t br_ccm_encrypt(br_crypto_t *c, const uint8_t key[BR_AES_KEY_LEN],
                        const uint8_t nonce[BR_CCM_NONCE_LEN],
                        const uint8_t *aad, size_t aad_len,
                        const uint8_t *pt, size_t pt_len,
                        uint8_t *ct_out, uint8_t tag_out[BR_CCM_TAG_LEN])
{
    if (c == NULL || !ccm_ptrs_ok(key, nonce, aad, aad_len, pt, pt_len, ct_out, tag_out)) {
        return BR_ERR_ARG;
    }
    if (!c->ready) {
        return BR_ERR_STATE;
    }
    if (!ccm_lens_ok(aad_len, pt_len)) {
        return BR_ERR_ARG;
    }
    ccm_state_t st;
    int ret = ccm_start(&st, key, nonce, aad, aad_len, pt_len);
    uint16_t blk = 1u;
    for (size_t off = 0u; ret == 0 && off < pt_len; off += CCM_BLOCK, blk++) {
        size_t n = pt_len - off;
        if (n > CCM_BLOCK) {
            n = CCM_BLOCK;
        }
        /* MAC the plaintext chunk before it may be overwritten (in place). */
        ret = ccm_mac_bytes(&st, &pt[off], n);
        if (ret == 0) {
            ret = ccm_keystream(&st, blk);
        }
        if (ret == 0) {
            for (size_t j = 0u; j < n; j++) {
                ct_out[off + j] = (uint8_t)(pt[off + j] ^ st.s[j]);
            }
        }
    }
    if (ret == 0) {
        ret = ccm_finish_tag(&st, tag_out);
    }
    ccm_wipe(&st);
    if (ret != 0) {
        if (pt_len > 0u && ct_out != pt) {
            mbedtls_platform_zeroize(ct_out, pt_len);
        }
        mbedtls_platform_zeroize(tag_out, BR_CCM_TAG_LEN);
        return BR_ERR_CRYPTO;
    }
    return BR_OK;
}

br_err_t br_ccm_decrypt(br_crypto_t *c, const uint8_t key[BR_AES_KEY_LEN],
                        const uint8_t nonce[BR_CCM_NONCE_LEN],
                        const uint8_t *aad, size_t aad_len,
                        const uint8_t *ct, size_t ct_len,
                        const uint8_t tag[BR_CCM_TAG_LEN], uint8_t *pt_out)
{
    if (c == NULL || !ccm_ptrs_ok(key, nonce, aad, aad_len, ct, ct_len, pt_out, tag)) {
        return BR_ERR_ARG;
    }
    if (!c->ready) {
        return BR_ERR_STATE;
    }
    if (!ccm_lens_ok(aad_len, ct_len)) {
        return BR_ERR_ARG;
    }
    ccm_state_t st;
    uint8_t calc[BR_CCM_TAG_LEN];
    int ret = ccm_start(&st, key, nonce, aad, aad_len, ct_len);
    uint16_t blk = 1u;
    for (size_t off = 0u; ret == 0 && off < ct_len; off += CCM_BLOCK, blk++) {
        size_t n = ct_len - off;
        if (n > CCM_BLOCK) {
            n = CCM_BLOCK;
        }
        ret = ccm_keystream(&st, blk);
        if (ret == 0) {
            for (size_t j = 0u; j < n; j++) {
                pt_out[off + j] = (uint8_t)(ct[off + j] ^ st.s[j]);
            }
            ret = ccm_mac_bytes(&st, &pt_out[off], n);
        }
    }
    if (ret == 0) {
        ret = ccm_finish_tag(&st, calc);
    }
    ccm_wipe(&st);
    br_err_t rc;
    if (ret != 0) {
        rc = BR_ERR_CRYPTO;
    } else {
        rc = (br_ct_equal(calc, tag, BR_CCM_TAG_LEN) == BR_OK) ? BR_OK : BR_ERR_AUTH;
    }
    mbedtls_platform_zeroize(calc, sizeof calc);
    if (rc != BR_OK && ct_len > 0u) {
        mbedtls_platform_zeroize(pt_out, ct_len); /* never release unauthenticated plaintext */
    }
    return rc;
}

/* ------------------------------------------------------------------------- */
/* hop_tag (8.3)                                                              */
/* ------------------------------------------------------------------------- */

br_err_t br_hop_tag(br_crypto_t *c, const uint8_t k_hop[BR_HOP_KEY_LEN],
                    const uint8_t *frame, size_t covered_len, uint8_t tag_out[BR_HOP_TAG_LEN])
{
    if (c == NULL || k_hop == NULL || frame == NULL || tag_out == NULL) {
        return BR_ERR_ARG;
    }
    if (!c->ready) {
        return BR_ERR_STATE;
    }
    /* 27 first (frame[1] is then readable), then the type-dependent 30 for SEEK (N18). */
    if (covered_len < (size_t)BR_HDR_LEN + BR_AUTH_TAG_LEN ||
        covered_len < br_hdr_len_for_type(frame[BR_OFF_TYPE]) + BR_AUTH_TAG_LEN) {
        return BR_ERR_ARG;
    }
    uint8_t mac[BR_SHA256_LEN];
    br_err_t rc = hmac3(c, k_hop, BR_HOP_KEY_LEN, frame, covered_len, NULL, 0u, NULL, 0u, mac);
    if (rc == BR_OK) {
        memcpy(tag_out, mac, BR_HOP_TAG_LEN);
    }
    mbedtls_platform_zeroize(mac, sizeof mac);
    return rc;
}

br_err_t br_hop_tag_verify(br_crypto_t *c, const uint8_t k_hop[BR_HOP_KEY_LEN],
                           const uint8_t *frame, size_t covered_len,
                           const uint8_t tag[BR_HOP_TAG_LEN])
{
    if (tag == NULL) {
        return BR_ERR_ARG;
    }
    uint8_t calc[BR_HOP_TAG_LEN];
    br_err_t rc = br_hop_tag(c, k_hop, frame, covered_len, calc);
    if (rc == BR_OK) {
        rc = (br_ct_equal(calc, tag, BR_HOP_TAG_LEN) == BR_OK) ? BR_OK : BR_ERR_AUTH;
    }
    mbedtls_platform_zeroize(calc, sizeof calc);
    return rc;
}

