/*
 * br_crypto.c - HKDF / HMAC-SHA256 / AES-128-CCM / hop_tag over mbedtls (spec 8.2, 8.3)
 * and the field-profile test-key blacklist (12.1).
 *
 * Heap: only br_crypto_init() allocates (mbedtls_md_setup). HMAC and HKDF
 * reuse c->hmac. AES-CCM is implemented here (RFC 3610 / SP 800-38C, M = 8,
 * L = 2, 13-byte nonce) on a stack mbedtls_aes_context; the reason and the
 * validation evidence are in br_crypto.h.
 *
 * Every secret-dependent scratch buffer is wiped with mbedtls_platform_zeroize
 * on every exit path. Tag checks use br_ct_equal().
 *
 * Error precedence (br_crypto.h, N20): NULL pointers -> BR_ERR_ARG, then an
 * uninitialised context -> BR_ERR_STATE, then length / range limits -> BR_ERR_ARG.
 */
#include <string.h>

#include "braid/br_crypto.h"
#include "braid/br_frame.h"

#include "mbedtls/aes.h"
#include "mbedtls/platform_util.h"
#include "mbedtls/sha256.h"

#include "br_internal.h"

#define CCM_BLOCK 16u
#define CCM_L     2u

/* ------------------------------------------------------------------------- */
/* Context                                                                    */
/* ------------------------------------------------------------------------- */

br_err_t br_crypto_init(br_crypto_t *c)
{
    if (c == NULL) {
        return BR_ERR_ARG;
    }
    memset(c, 0, sizeof *c);
    mbedtls_md_init(&c->hmac);

    const mbedtls_md_info_t *info = mbedtls_md_info_from_type(MBEDTLS_MD_SHA256);
    if (info == NULL) {
        mbedtls_md_free(&c->hmac);
        mbedtls_platform_zeroize(c, sizeof *c);
        return BR_ERR_CRYPTO;
    }
    int ret = mbedtls_md_setup(&c->hmac, info, 1);
    if (ret != 0) {
        mbedtls_md_free(&c->hmac);
        mbedtls_platform_zeroize(c, sizeof *c);
        return (ret == MBEDTLS_ERR_MD_ALLOC_FAILED) ? BR_ERR_NO_MEM : BR_ERR_CRYPTO;
    }
    c->ready = true;
    return BR_OK;
}

void br_crypto_free(br_crypto_t *c)
{
    if (c == NULL) {
        return;
    }
    if (c->ready) {
        mbedtls_md_free(&c->hmac);
    }
    mbedtls_platform_zeroize(c, sizeof *c);
}

/* ------------------------------------------------------------------------- */
/* HMAC-SHA256 and HKDF (RFC 2104, RFC 5869)                                  */
/* ------------------------------------------------------------------------- */

/* HMAC over up to three concatenated parts; NULL part allowed iff its len is 0. */
static br_err_t hmac3(br_crypto_t *c, const uint8_t *key, size_t key_len,
                      const uint8_t *p1, size_t n1, const uint8_t *p2, size_t n2,
                      const uint8_t *p3, size_t n3, uint8_t mac_out[BR_SHA256_LEN])
{
    static const uint8_t empty = 0u; /* mbedtls never gets a NULL pointer */
    int ret = mbedtls_md_hmac_starts(&c->hmac, (key_len > 0u) ? key : &empty, key_len);
    if (ret == 0 && n1 > 0u) {
        ret = mbedtls_md_hmac_update(&c->hmac, p1, n1);
    }
    if (ret == 0 && n2 > 0u) {
        ret = mbedtls_md_hmac_update(&c->hmac, p2, n2);
    }
    if (ret == 0 && n3 > 0u) {
        ret = mbedtls_md_hmac_update(&c->hmac, p3, n3);
    }
    if (ret == 0) {
        ret = mbedtls_md_hmac_finish(&c->hmac, mac_out);
    }
    if (ret != 0) {
        mbedtls_platform_zeroize(mac_out, BR_SHA256_LEN);
        return BR_ERR_CRYPTO;
    }
    return BR_OK;
}

br_err_t br_hmac_sha256(br_crypto_t *c, const uint8_t *key, size_t key_len,
                        const uint8_t *data, size_t len, uint8_t mac_out[BR_SHA256_LEN])
{
    if (c == NULL || mac_out == NULL || (key == NULL && key_len > 0u) ||
        (data == NULL && len > 0u)) {
        return BR_ERR_ARG;
    }
    if (!c->ready) {
        return BR_ERR_STATE;
    }
    return hmac3(c, key, key_len, data, len, NULL, 0u, NULL, 0u, mac_out);
}

br_err_t br_hkdf_extract(br_crypto_t *c, const uint8_t *salt, size_t salt_len,
                         const uint8_t *ikm, size_t ikm_len, uint8_t prk_out[BR_SHA256_LEN])
{
    static const uint8_t zero_salt[BR_SHA256_LEN] = {0};
    if (c == NULL || prk_out == NULL || (salt == NULL && salt_len > 0u) ||
        (ikm == NULL && ikm_len > 0u)) {
        return BR_ERR_ARG;
    }
    if (!c->ready) {
        return BR_ERR_STATE;
    }
    if (salt_len == 0u) {
        /* RFC 5869 2.2: absent salt = HashLen zero bytes (same HMAC key as an empty one). */
        salt = zero_salt;
        salt_len = sizeof zero_salt;
    }
    return hmac3(c, salt, salt_len, ikm, ikm_len, NULL, 0u, NULL, 0u, prk_out);
}

br_err_t br_hkdf_expand(br_crypto_t *c, const uint8_t *prk, size_t prk_len,
                        const uint8_t *info, size_t info_len, uint8_t *okm_out, size_t okm_len)
{
    if (c == NULL || prk == NULL || okm_out == NULL || (info == NULL && info_len > 0u)) {
        return BR_ERR_ARG;
    }
    if (!c->ready) {
        return BR_ERR_STATE;
    }
    if (prk_len < BR_SHA256_LEN || okm_len == 0u || okm_len > BR_HKDF_MAX_OKM) {
        return BR_ERR_ARG;
    }
    uint8_t t[BR_SHA256_LEN];
    size_t t_len = 0u;
    size_t done = 0u;
    uint8_t ctr = 0u;
    br_err_t rc = BR_OK;
    while (done < okm_len) {
        ctr++;
        rc = hmac3(c, prk, prk_len, t, t_len, info, info_len, &ctr, 1u, t);
        if (rc != BR_OK) {
            mbedtls_platform_zeroize(okm_out, okm_len);
            break;
        }
        t_len = BR_SHA256_LEN;
        size_t n = okm_len - done;
        if (n > BR_SHA256_LEN) {
            n = BR_SHA256_LEN;
        }
        memcpy(&okm_out[done], t, n);
        done += n;
    }
    mbedtls_platform_zeroize(t, sizeof t);
    return rc;
}

br_err_t br_hkdf_sha256(br_crypto_t *c, const uint8_t *salt, size_t salt_len,
                        const uint8_t *ikm, size_t ikm_len,
                        const uint8_t *info, size_t info_len, uint8_t *okm_out, size_t okm_len)
{
    if (c == NULL || okm_out == NULL || (salt == NULL && salt_len > 0u) ||
        (ikm == NULL && ikm_len > 0u) || (info == NULL && info_len > 0u)) {
        return BR_ERR_ARG;
    }
    if (!c->ready) {
        return BR_ERR_STATE;
    }
    if (okm_len == 0u || okm_len > BR_HKDF_MAX_OKM) {
        return BR_ERR_ARG;
    }
    uint8_t prk[BR_SHA256_LEN];
    br_err_t rc = br_hkdf_extract(c, salt, salt_len, ikm, ikm_len, prk);
    if (rc == BR_OK) {
        rc = br_hkdf_expand(c, prk, sizeof prk, info, info_len, okm_out, okm_len);
    }
    mbedtls_platform_zeroize(prk, sizeof prk);
    return rc;
}

